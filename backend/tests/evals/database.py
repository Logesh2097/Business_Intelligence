def snapshot(conn: psycopg.Connection[dict[str, Any]]) -> dict[str, Any]:
    """Counts, totals, relationships and date ranges, as plain values for baseline.yaml."""

    def plain(value: Any) -> Any:
        return float(value) if isinstance(value, Decimal) else value

    return {
        name: [{k: plain(v) for k, v in row.items()} for row in conn.execute(query).fetchall()]  # type: ignore[arg-type]
        for name, query in SNAPSHOT_SQL.items()
    }


def load_baseline() -> dict[str, Any] | None:
    if not BASELINE.exists():
        return None
    loaded: dict[str, Any] = yaml.safe_load(BASELINE.read_text())
    return loaded


def check_baseline(conn: psycopg.Connection[dict[str, Any]], data: Data) -> list[str]:
    """Everything in which this database differs from the approved baseline."""
    baseline = load_baseline()
    if baseline is None:
        return ["baseline.yaml is missing"]
    problems = []
    inputs = {"reference_date": str(REFERENCE_DATE), "seed": SEED, "days": DAYS}
    if baseline["inputs"] != inputs:
        problems.append(f"inputs: baseline {baseline['inputs']}, code {inputs}")
    if baseline["fingerprint"] != fingerprint(data):
        problems.append("fingerprint: the generated rows are not the approved rows")
    problems += differences(conn, data)
    taken = snapshot(conn)
    for part in SNAPSHOT_SQL:
        if baseline[part] != taken[part]:
            problems.append(f"{part}: differs from the baseline")
    return problems
