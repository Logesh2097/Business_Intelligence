"""The evaluation database `bi_eval`: created here, from fixed inputs, and nowhere else.

The golden set's expected figures are only true for one exact set of rows. The demo
database cannot be that set: `make db-seed` replaces it with data for the day it is
run. So the evaluation builds its own database with the project's own generator and
loader, from three fixed inputs, and refuses to go on unless the result is the
approved baseline (baseline.yaml).

Safety, in this order:
- the database name is a constant; no function here takes a name to drop;
- it must not be a database the application is configured to use, nor a protected one;
- only dev and test, only a local server;
- an existing `bi_eval` is dropped only if it carries the marker this module set when
  it created it; otherwise it is somebody else's and we stop;
- CREATE and DROP DATABASE are sent on a connection to the maintenance database, not
  to the demo database;
- before rows are loaded (the loader starts with TRUNCATE) the connection must answer
  current_database() = 'bi_eval'.

The demo database is only ever opened by `read_only()`, which makes PostgreSQL itself
reject a write.
"""

from __future__ import annotations

import hashlib
import sys
from datetime import date, datetime, timezone
from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import Any

import psycopg
import yaml
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict, make_conninfo
from psycopg.rows import dict_row

from app.core.config import Settings
from app.seed.generate import Data, generate
from app.seed.load import COLUMNS, load
from app.store.migrate import migrate

EVAL_DATABASE = "bi_eval"
REFERENCE_DATE = date(2026, 11, 11)  # "today" for every evaluation run
SEED = 42
DAYS = 120

MARKER = "BI evaluation database: generated by backend/tests/evals, safe to drop"
MAINTENANCE_DATABASE = "postgres"
PROTECTED = frozenset({"bi", "bi_test", "postgres", "template0", "template1"})
LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1", "::1"})
BASELINE = Path(__file__).parent / "baseline.yaml"


class EvalDatabaseError(RuntimeError):
    """The evaluation database cannot be used. Nothing was dropped or changed."""


# -- which database, and is it safe to touch -------------------------------------------


def database_of(dsn: str) -> str:
    return str(conninfo_to_dict(dsn).get("dbname") or "")


def check_target(name: str, settings: Settings) -> None:
    """Raise unless `name` may be dropped and recreated. Opens no connection."""
    if name != "bi_eval":
        raise EvalDatabaseError(f"refused: only bi_eval may be recreated, not {name!r}")
    if name in PROTECTED:
        raise EvalDatabaseError(f"refused: {name!r} is a protected database")
    if not settings.relaxed:
        raise EvalDatabaseError(f"refused: the environment is {settings.env!r}, not dev or test")
    if not settings.pg_owner_dsn:
        raise EvalDatabaseError("BI_PG_OWNER_DSN is not set: bi_eval is created as the owner")
    for label, dsn in (
        ("BI_PG_DSN", settings.pg_dsn),
        ("BI_PG_READONLY_DSN", settings.pg_readonly_dsn),
        ("BI_PG_OWNER_DSN", settings.pg_owner_dsn),
    ):
        info = conninfo_to_dict(dsn)
        if str(info.get("dbname") or "") == name:
            raise EvalDatabaseError(f"refused: {label} already points at {name!r}")
        host = str(info.get("host") or "")
        if host not in LOCAL_HOSTS and not host.startswith("/"):
            raise EvalDatabaseError(f"refused: {label} is not a local server")


def eval_settings(base: Settings, *, keep_model: bool = False) -> Settings:
    """A copy of the settings, in memory only, pointing at bi_eval with today pinned.

    Nothing is written anywhere: .env and the normal settings are untouched.
    """
    check_target(EVAL_DATABASE, base)

    def on_eval(dsn: str) -> str:
        return make_conninfo(dsn, dbname=EVAL_DATABASE)

    update: dict[str, Any] = {
        "pg_dsn": on_eval(base.pg_dsn),
        "pg_readonly_dsn": on_eval(base.pg_readonly_dsn),
        "pg_owner_dsn": on_eval(base.pg_owner_dsn),
        "fake_today": REFERENCE_DATE,
    }
    if not keep_model:
        update["openai_api_key"] = ""  # the dataset checks never call a real model
    return base.model_copy(update=update)


def confirm_is_eval(dsn: str) -> None:
    """The last check before anything is written: is this really bi_eval?"""
    if database_of(dsn) != EVAL_DATABASE:
        raise EvalDatabaseError(f"refused: {database_of(dsn)!r} is not {EVAL_DATABASE}")
    with psycopg.connect(dsn) as conn:
        row = conn.execute("SELECT current_database()").fetchone()
    if row is None or row[0] != EVAL_DATABASE:
        raise EvalDatabaseError(f"refused: connected to {row and row[0]!r}, not {EVAL_DATABASE}")


def read_only(dsn: str) -> psycopg.Connection[dict[str, Any]]:
    """A connection on which PostgreSQL rejects every write."""
    return psycopg.connect(dsn, row_factory=dict_row, options="-c default_transaction_read_only=on")


# -- creating it -------------------------------------------------------------------------


def recreate(base: Settings) -> tuple[Settings, Data]:
    """Drop (if ours) and rebuild bi_eval from the fixed inputs. Returns its settings."""
    check_target(EVAL_DATABASE, base)
    data = generate(REFERENCE_DATE, DAYS, seed=SEED)
    expected = load_baseline()
    if expected is not None and fingerprint(data) != expected["fingerprint"]:
        raise EvalDatabaseError(
            "the generator no longer produces the approved data (fingerprint "
            f"{fingerprint(data)[:16]}, baseline {expected['fingerprint'][:16]}, "
            f"Python {sys.version_info.major}.{sys.version_info.minor}). "
            "Expected values are not to be changed to fit: find what changed."
        )

    name = sql.Identifier(EVAL_DATABASE)
    admin = make_conninfo(base.pg_owner_dsn, dbname=MAINTENANCE_DATABASE)
    with psycopg.connect(admin, autocommit=True) as conn:
        found = conn.execute(
            "SELECT shobj_description(oid, 'pg_database') FROM pg_database WHERE datname = %s",
            (EVAL_DATABASE,),
        ).fetchone()
        if found is not None:
            if found[0] != MARKER:
                raise EvalDatabaseError(
                    f"a database named {EVAL_DATABASE} exists and was not created by the "
                    "evaluation (it has no marker). It was left alone."
                )
            conn.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(name))
        conn.execute(sql.SQL("CREATE DATABASE {}").format(name))
        conn.execute(sql.SQL("COMMENT ON DATABASE {} IS {}").format(name, sql.Literal(MARKER)))
        conn.execute(sql.SQL("REVOKE ALL ON DATABASE {} FROM PUBLIC").format(name))
        conn.execute(sql.SQL("GRANT CONNECT ON DATABASE {} TO bi_app, bi_readonly").format(name))

    settings = eval_settings(base)
    confirm_is_eval(settings.pg_owner_dsn)
    migrate(settings.pg_owner_dsn)
    confirm_is_eval(settings.pg_owner_dsn)  # the loader truncates: ask once more
    load(settings.pg_owner_dsn, data)
    return settings, data


# -- is it the approved data -------------------------------------------------------------


def fingerprint(data: Data) -> str:
    """A hash of every generated row, in loading order."""
    digest = hashlib.sha256()
    for table in COLUMNS:
        for row in data.tables.get(table, []):
            digest.update(repr(tuple(str(value) for value in row)).encode())
    return digest.hexdigest()


def _canonical(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, datetime):
        return value.astimezone(timezone.utc).isoformat()
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, (int, float, Decimal)):
        return format(Decimal(str(value)).normalize(), "f")
    text = str(value)
    try:
        return format(Decimal(text).normalize(), "f")
    except InvalidOperation:
        return text


def differences(conn: psycopg.Connection[Any], data: Data) -> list[str]:
    """Tables whose rows in the database are not exactly the generated rows.

    Every column the generator writes is compared, row for row. Columns the database
    fills from its clock (created_at, updated_at) are not written by the generator
    and so are not compared; no golden question may depend on them.
    """
    found = []
    for table, columns in COLUMNS.items():
        generated = sorted(tuple(_canonical(v) for v in row) for row in data.tables.get(table, []))
        cursor = conn.execute(sql.SQL("SELECT {} FROM {}").format(sql.SQL(columns), sql.SQL(table)))
        stored = sorted(
            tuple(_canonical(v) for v in (row.values() if isinstance(row, dict) else row))
            for row in cursor.fetchall()
        )
        if generated != stored:
            found.append(f"{table}: generated {len(generated)} rows, database {len(stored)}")
    return found


